    function getLanguage() {
        const stored = localStorage.getItem(storageKey);
        return supported.has(stored) ? stored : "en";
    }

    function setLanguage(language) {
        const nextLanguage = supported.has(language) ? language : "en";
        localStorage.setItem(storageKey, nextLanguage);
        applyStaticTranslations();
        document.dispatchEvent(new CustomEvent("polytype-app-language-changed", {
            detail: { language: nextLanguage }
        }));
    }

    function t(key, params = {}) {
        const language = getLanguage();
        const template =
            dictionaries[language]?.[key] ??
            dictionaries.en[key] ??
            key;

        return String(template).replace(/\{(\w+)\}/g, (_, name) =>
            Object.prototype.hasOwnProperty.call(params, name) ? params[name] : `{${name}}`
        );
    }

    function languageLabel(language) {
        return t(`language.${language}`) || t("language.fallback");
    }

    function applyStaticTranslations(root = document) {
        const language = getLanguage();
        document.documentElement.lang = language;

        root.querySelectorAll("[data-i18n]").forEach(element => {
            element.textContent = t(element.dataset.i18n);
        });

        root.querySelectorAll("[data-i18n-html]").forEach(element => {
            element.innerHTML = t(element.dataset.i18nHtml);
        });

        root.querySelectorAll("[data-i18n-aria-label]").forEach(element => {
            element.setAttribute("aria-label", t(element.dataset.i18nAriaLabel));
        });

        root.querySelectorAll("[data-i18n-title]").forEach(element => {
            element.setAttribute("title", t(element.dataset.i18nTitle));
        });

        root.querySelectorAll("[data-i18n-placeholder]").forEach(element => {
            element.setAttribute("placeholder", t(element.dataset.i18nPlaceholder));
        });

        const title = document.querySelector("title[data-i18n]");
        if (title) document.title = title.textContent;
    }

    window.PolytypeI18n = {
        storageKey,
        getLanguage,
        setLanguage,
        t,
        languageLabel,
        applyStaticTranslations
    };

    document.addEventListener("DOMContentLoaded", () => applyStaticTranslations());
