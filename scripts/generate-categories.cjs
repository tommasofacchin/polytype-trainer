// One-off generator for decks/categories.js.
//
// Word decks are aligned across every language: the same numeric word_id
// suffix (1-300) always maps to the same concept and the same unlock_level
// (level = ceil(suffix / 5), 5 words per level). This script groups the 60
// levels into 15 themed categories, shuffles the drop order within each
// category with a fixed seed (so it only needs to be generated once, and
// every client/session sees the same order), and writes the result as a
// plain browser global so it can be loaded like decks/index.js.
//
// Run with: node scripts/generate-categories.cjs

const fs = require("fs");
const path = require("path");

const WORDS_PER_LEVEL = 5;
const TOTAL_LEVELS = 60;
const TOTAL_WORDS = TOTAL_LEVELS * WORDS_PER_LEVEL;

const CATEGORIES = [
  { id: "greetings", labelKey: "categories.greetings", levels: [1, 2, 56, 57] },
  { id: "peopleFamily", labelKey: "categories.peopleFamily", levels: [5, 6, 43] },
  { id: "describingYourself", labelKey: "categories.describingYourself", levels: [7, 8, 9, 10] },
  { id: "verbs", labelKey: "categories.verbs", levels: [11, 12, 46, 47, 48, 49, 50] },
  { id: "timeCalendar", labelKey: "categories.timeCalendar", levels: [14, 15, 33, 34, 35] },
  { id: "numbersColors", labelKey: "categories.numbersColors", levels: [16, 17, 18, 19, 41, 42] },
  { id: "questionsConnectors", labelKey: "categories.questionsConnectors", levels: [13, 20, 21, 22, 23] },
  { id: "cityHome", labelKey: "categories.cityHome", levels: [4, 24, 25, 60] },
  { id: "foodMeals", labelKey: "categories.foodMeals", levels: [3, 26, 27, 28, 29] },
  { id: "bodyClothes", labelKey: "categories.bodyClothes", levels: [30, 31, 32] },
  { id: "seasonsWeather", labelKey: "categories.seasonsWeather", levels: [36, 37] },
  { id: "travel", labelKey: "categories.travel", levels: [38, 39, 40] },
  { id: "workSchool", labelKey: "categories.workSchool", levels: [44, 45] },
  { id: "feelingsQualities", labelKey: "categories.feelingsQualities", levels: [51, 52, 53, 54, 55] },
  { id: "shoppingHealth", labelKey: "categories.shoppingHealth", levels: [58, 59] }
];

function mulberry32(seed) {
  let a = seed;
  return function random() {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function seededShuffle(array, seed) {
  const random = mulberry32(seed);
  const result = array.slice();
  for (let i = result.length - 1; i > 0; i -= 1) {
    const j = Math.floor(random() * (i + 1));
    [result[i], result[j]] = [result[j], result[i]];
  }
  return result;
}

function suffixesForLevel(level) {
  const start = (level - 1) * WORDS_PER_LEVEL + 1;
  return Array.from({ length: WORDS_PER_LEVEL }, (_, i) => start + i);
}

function buildCategories() {
  const seenLevels = new Set();
  const seenSuffixes = new Set();

  const built = CATEGORIES.map((category, index) => {
    const suffixes = category.levels.flatMap(level => {
      if (level < 1 || level > TOTAL_LEVELS) {
        throw new Error(`Category "${category.id}" references out-of-range level ${level}`);
      }
      if (seenLevels.has(level)) {
        throw new Error(`Level ${level} assigned to more than one category (duplicate in "${category.id}")`);
      }
      seenLevels.add(level);
      return suffixesForLevel(level);
    });

    suffixes.forEach(suffix => {
      if (seenSuffixes.has(suffix)) {
        throw new Error(`word suffix ${suffix} assigned to more than one category`);
      }
      seenSuffixes.add(suffix);
    });

    return {
      id: category.id,
      labelKey: category.labelKey,
      order: index,
      size: suffixes.length,
      wordSuffixes: seededShuffle(suffixes, 1000 + index)
    };
  });

  for (let level = 1; level <= TOTAL_LEVELS; level += 1) {
    if (!seenLevels.has(level)) {
      throw new Error(`Level ${level} is not covered by any category`);
    }
  }

  if (seenSuffixes.size !== TOTAL_WORDS) {
    throw new Error(`Expected ${TOTAL_WORDS} covered word suffixes, got ${seenSuffixes.size}`);
  }

  for (let suffix = 1; suffix <= TOTAL_WORDS; suffix += 1) {
    if (!seenSuffixes.has(suffix)) {
      throw new Error(`word suffix ${suffix} is not covered by any category`);
    }
  }

  return built;
}

function main() {
  const categories = buildCategories();
  const totalWords = categories.reduce((sum, category) => sum + category.size, 0);

  if (totalWords !== TOTAL_WORDS) {
    throw new Error(`Total words across categories is ${totalWords}, expected ${TOTAL_WORDS}`);
  }

  const outputPath = path.join(__dirname, "..", "decks", "categories.js");
  const banner =
    "// Generated by scripts/generate-categories.cjs. Do not edit by hand -\n" +
    "// change the CATEGORIES list in that script and re-run it instead.\n";
  // Isomorphic: browser pages load it as a plain global (<script src>), while
  // api/*.js (Node/Vercel serverless) needs the same data via require() to
  // validate word suffixes and migrate legacy unlock progress server-side.
  const body =
    `const CATEGORIES_DATA = ${JSON.stringify(categories, null, 2)};\n` +
    `if (typeof window !== "undefined") { window.POLYTYPE_CATEGORIES = CATEGORIES_DATA; }\n` +
    `if (typeof module !== "undefined" && module.exports) { module.exports = CATEGORIES_DATA; }\n`;

  fs.writeFileSync(outputPath, banner + body, "utf8");

  console.log(`Wrote ${categories.length} categories covering ${totalWords} words to ${outputPath}`);
  categories.forEach(category => {
    console.log(`  ${String(category.order).padStart(2, "0")}  ${category.id.padEnd(20)} size=${category.size}`);
  });
}

main();
